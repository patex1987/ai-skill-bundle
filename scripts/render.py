#!/usr/bin/env python3
"""Render a repository's canonical .ai/ guidance into assistant-specific folders.

Vendored into each repository as .ai/render.py by the catalog installer. It
replaces per-repository sync scripts. Python standard library only.

    python3 .ai/render.py            # write outputs
    python3 .ai/render.py --check    # exit 1 if outputs are stale (CI)
    python3 .ai/render.py --dry-run  # list outputs without writing

Canonical inputs (all under .ai/):
    bundle.json          targets, routing overrides, invocation overrides
    routing.json         tier -> per-tool model and effort defaults
    project-guidance.md  always-on repository context (optional)
    skills/<name>/       Agent Skills directories (SKILL.md + resources)
    agents/<name>.md     review/worker agent definitions
    rules/<name>.md      rules with description/always-apply/paths frontmatter
    overlays/<name>.md   repository-specific additions to a catalog skill
"""
import argparse
import json
import os
from pathlib import Path, PurePosixPath
import re
import shutil
import sys

RENDERER_VERSION = '2.1.0'
HEADER_MD = '<!-- Generated by .ai/render.py from .ai/. Edit the canonical source and re-render. -->'
HEADER_TOML = '# Generated by .ai/render.py from .ai/. Edit the canonical source and re-render.'
MANIFEST = 'generated-outputs.txt'
TARGETS = ('agents-md', 'claude', 'codex', 'cursor', 'gemini')
REMOVED_TARGETS = {'roo': 'Roo support was removed in renderer 2.1.0; delete "roo" from targets'}
DEFAULT_TARGETS = ['agents-md', 'claude', 'codex', 'cursor', 'gemini']
TIERS = ('fast', 'balanced', 'deep')
EFFORTS = ('low', 'medium', 'high', 'xhigh', 'max')
NAME_RE = re.compile(r'^[a-z0-9]+(-[a-z0-9]+)*$')

# Every generated path must match one of these namespaces. Cleanup refuses
# anything else, so a corrupted manifest cannot delete unrelated files.
MANAGED_PATTERNS = [re.compile(p) for p in (
    r'^AGENTS\.md$',
    r'^\.claude/CLAUDE\.md$', r'^\.claude/(skills|agents|rules)/[a-z0-9-]+(\.md)?$',
    r'^\.agents/skills/[a-z0-9-]+$',
    r'^\.codex/agents/[a-z0-9-]+\.toml$',
    r'^\.cursor/rules/[a-z0-9-]+\.mdc$', r'^\.cursor/agents/[a-z0-9-]+\.md$',
    r'^GEMINI\.md$', r'^\.gemini/agents/[a-z0-9-]+\.md$',

)]
# Paths written by legacy sync.sh scripts that this renderer no longer produces.
# They are removed only when listed in the previous manifest.
LEGACY_PATTERNS = [re.compile(p) for p in (
    r'^\.codex/AGENTS\.md$', r'^\.codex/(rules|skills)/[A-Za-z0-9_.-]+$',
    r'^\.cursor/skills/[A-Za-z0-9_.-]+$', r'^\.gemini/(rules|skills)/[A-Za-z0-9_.-]+$',
    r'^\.gemini/GEMINI\.md$',
    r'^\.roo/(rules|skills)/[A-Za-z0-9_.-]+$',
)]


class RenderError(Exception):
    pass


# --- Frontmatter -------------------------------------------------------------
# A deliberately small YAML subset: `key: scalar`, `key: [a, b]`, and one level
# of nested `key:` maps (used for `metadata`). Anything else is rejected rather
# than guessed, so canonical files stay portable across tools.

def _scalar(raw, where):
    raw = raw.strip()
    if raw.startswith('[') and raw.endswith(']'):
        inner = raw[1:-1].strip()
        return [_scalar(item, where) for item in _split_list(inner)] if inner else []
    if len(raw) >= 2 and raw[0] == raw[-1] and raw[0] in '"\'':
        body = raw[1:-1]
        return body.replace("''", "'") if raw[0] == "'" else json.loads(raw)
    if raw in ('true', 'false'):
        return raw == 'true'
    if raw.startswith(('{', '|', '>', '&', '*', '!')):
        raise RenderError(f'{where}: unsupported YAML construct {raw[:12]!r}')
    return raw


def _split_list(inner):
    items, depth, quote, current = [], 0, None, ''
    for char in inner:
        if quote:
            quote = None if char == quote else quote
        elif char in '"\'':
            quote = char
        elif char == ',' and depth == 0:
            items.append(current)
            current = ''
            continue
        current += char
    items.append(current)
    return [item for item in items if item.strip()]


def parse_frontmatter(text, where):
    if not text.startswith('---\n'):
        raise RenderError(f'{where}: missing frontmatter')
    end = text.find('\n---\n', 4)
    if end == -1:
        if text.endswith('\n---'):
            end = len(text) - 4
        else:
            raise RenderError(f'{where}: unterminated frontmatter')
    data, parent = {}, None
    for number, line in enumerate(text[4:end].split('\n'), start=2):
        if not line.strip() or line.lstrip().startswith('#'):
            continue
        indented = line.startswith((' ', '\t'))
        key, sep, value = line.strip().partition(':')
        if not sep or not re.fullmatch(r'[A-Za-z_][A-Za-z0-9_.-]*', key):
            raise RenderError(f'{where}:{number}: expected "key: value"')
        if indented:
            if parent is None:
                raise RenderError(f'{where}:{number}: unexpected indentation')
            data[parent][key] = _scalar(value, f'{where}:{number}')
        elif value.strip():
            data[key] = _scalar(value, f'{where}:{number}')
            parent = None
        else:
            data[key] = {}
            parent = key
    return data, text[end + 5:] if end + 5 <= len(text) else ''


def _quote(value):
    if isinstance(value, bool):
        return 'true' if value else 'false'
    if isinstance(value, int):
        return str(value)
    if isinstance(value, list):
        return '[' + ', '.join(_quote(v) for v in value) + ']'
    text = str(value)
    if text == '' or re.search(r'[:#\[\]{},&*!|>\'"%@`]', text) or text != text.strip() \
            or text in ('true', 'false', 'null', 'yes', 'no'):
        return json.dumps(text, ensure_ascii=False)
    return text


def dump_frontmatter(data):
    lines = ['---']
    for key, value in data.items():
        if isinstance(value, dict):
            if value:
                lines.append(f'{key}:')
                lines.extend(f'  {k}: {_quote(v)}' for k, v in value.items())
        elif value is not None:
            lines.append(f'{key}: {_quote(value)}')
    lines.append('---')
    return '\n'.join(lines) + '\n'


# --- Loading canonical content ----------------------------------------------

def read_json(path, default=None):
    if not path.exists():
        if default is not None:
            return default
        raise RenderError(f'missing {path}')
    try:
        return json.loads(path.read_text())
    except json.JSONDecodeError as error:
        raise RenderError(f'{path}: invalid JSON: {error}') from error


def load_config(ai):
    bundle = read_json(ai / 'bundle.json', {})
    routing = read_json(ai / 'routing.json', {'tiers': {}, 'tools': {}})
    targets = bundle.get('targets', DEFAULT_TARGETS)
    for target in targets:
        if target in REMOVED_TARGETS:
            raise RenderError(f'bundle.json: {REMOVED_TARGETS[target]}')
    unknown = sorted(set(targets) - set(TARGETS))
    if unknown:
        raise RenderError(f'bundle.json: unknown targets {unknown}; known: {list(TARGETS)}')
    tools = {tool: dict(cfg) for tool, cfg in routing.get('tools', {}).items()}
    for tool, models in bundle.get('routing', {}).get('models', {}).items():
        tools.setdefault(tool, {}).setdefault('models', {})
        tools[tool]['models'] = {**tools[tool].get('models', {}), **models}
    apply_modes = {'skills': 'advisory', 'agents': 'enforce', **bundle.get('routing', {}).get('apply', {})}
    for kind, mode in apply_modes.items():
        if mode not in ('advisory', 'enforce'):
            raise RenderError(f'bundle.json: routing.apply.{kind} must be advisory or enforce')
    return {
        'targets': targets,
        'tiers': routing.get('tiers', {}),
        'tools': tools,
        'apply': apply_modes,
        'routing_overrides': bundle.get('routing', {}).get('overrides', {}),
        'invocation': bundle.get('invocation', {}),
    }


def _routing(meta, name, config):
    override = config['routing_overrides'].get(name, {})
    tier = override.get('tier', meta.get('routing-tier'))
    effort = override.get('effort', meta.get('routing-effort'))
    if tier is not None and tier not in TIERS:
        raise RenderError(f'{name}: routing tier must be one of {TIERS}, got {tier!r}')
    if tier and not effort:
        effort = config['tiers'].get(tier, {}).get('effort')
    return tier, effort


def load_entities(ai, config):
    entities = {'skills': [], 'agents': [], 'rules': []}
    for skill_dir in sorted((ai / 'skills').glob('*')) if (ai / 'skills').is_dir() else []:
        if not skill_dir.is_dir():
            continue
        skill_file = skill_dir / 'SKILL.md'
        if not skill_file.is_file():
            raise RenderError(f'{skill_dir}: missing SKILL.md')
        front, body = parse_frontmatter(skill_file.read_text(), str(skill_file))
        name = front.get('name')
        if name != skill_dir.name or not NAME_RE.match(name or ''):
            raise RenderError(f'{skill_file}: name must be kebab-case and match its directory')
        meta = front.get('metadata', {})
        invocation = config['invocation'].get(name, meta.get('invocation', 'auto'))
        if invocation not in ('auto', 'explicit'):
            raise RenderError(f'{name}: invocation must be auto or explicit')
        tier, effort = _routing(meta, name, config)
        overlay = ai / 'overlays' / f'{name}.md'
        entities['skills'].append({
            'name': name, 'dir': skill_dir, 'front': front, 'body': body, 'meta': meta,
            'invocation': invocation, 'tier': tier, 'effort': effort,
            'fork': meta.get('context') == 'fork', 'overlay': overlay if overlay.is_file() else None,
        })
    for kind in ('agents', 'rules'):
        folder = ai / kind
        for file in sorted(folder.glob('*.md')) if folder.is_dir() else []:
            front, body = parse_frontmatter(file.read_text(), str(file))
            name = front.get('name', file.stem)
            if name != file.stem or not NAME_RE.match(name):
                raise RenderError(f'{file}: name must be kebab-case and match its filename')
            if not front.get('description'):
                raise RenderError(f'{file}: description is required')
            meta = front.get('metadata', {})
            entry = {'name': name, 'front': front, 'body': body.lstrip('\n'), 'meta': meta}
            if kind == 'agents':
                entry['tier'], entry['effort'] = _routing(meta, name, config)
                entry['access'] = front.get('access', 'read-only')
                if entry['access'] not in ACCESS_LEVELS:
                    raise RenderError(f'{file}: access must be one of {ACCESS_LEVELS}')
            entities[kind].append(entry)
    known = {skill['name'] for skill in entities['skills']}
    routable = known | {agent['name'] for agent in entities['agents']}
    for name in config['routing_overrides']:
        if name not in routable:
            raise RenderError(f'bundle.json: routing.overrides names unknown skill or agent {name!r}')
    for name, override in config['routing_overrides'].items():
        if override.get('effort') not in (None, *EFFORTS):
            raise RenderError(f'bundle.json: routing.overrides.{name}.effort must be one of {EFFORTS}')
    for name in config['invocation']:
        if name not in known:
            raise RenderError(f'bundle.json: invocation names unknown skill {name!r}')
    overlays = ai / 'overlays'
    for overlay in sorted(overlays.glob('*.md')) if overlays.is_dir() else []:
        if overlay.stem not in known:
            raise RenderError(f'{overlay}: overlay for unknown skill {overlay.stem!r}')
    return entities


# --- Rendering ---------------------------------------------------------------

def tool_model(config, tool, tier):
    """Return the configured model for a tool and tier, or None to inherit."""
    if not tier:
        return None
    return config['tools'].get(tool, {}).get('models', {}).get(tier)


def tool_effort(config, tool, effort):
    supported = config['tools'].get(tool, {}).get('efforts', [])
    return effort if effort in supported else None


def overlay_note(skill):
    note = ''
    if skill['invocation'] == 'explicit':
        note += ('\n> **Explicit only:** use this skill only when the user names it or explicitly asks '
                 'for what it does. Do not apply it on your own initiative.\n')
    if not skill['overlay']:
        return note
    return note + (f"\n> **Repository conventions:** read `.ai/overlays/{skill['name']}.md` before applying this "
            'skill. It records this repository\'s paths, commands, and decisions, and it takes precedence '
            'over the generic guidance below.\n')


def skill_files(skill, front, extra=None):
    """Map relative path -> bytes for a rendered skill directory."""
    files = {}
    for file in sorted(skill['dir'].rglob('*')):
        if file.is_symlink():
            raise RenderError(f'{file}: symlinks are not allowed in skills')
        if file.is_file():
            files[file.relative_to(skill['dir']).as_posix()] = (file.read_bytes(), os.access(file, os.X_OK))
    body = f'\n{HEADER_MD}\n' + overlay_note(skill) + skill['body']
    files['SKILL.md'] = ((dump_frontmatter(front) + body).encode(), False)
    for path, content in (extra or {}).items():
        files[path] = (content.encode(), False)
    return files


def claude_skill_front(skill, config):
    front = {k: v for k, v in skill['front'].items()}
    if skill['invocation'] == 'explicit':
        front['disable-model-invocation'] = True
    if config['apply']['skills'] == 'enforce' or skill['fork']:
        effort = tool_effort(config, 'claude', skill['effort'])
        if effort:
            front['effort'] = effort
    if skill['fork']:
        front['context'] = 'fork'
        model = tool_model(config, 'claude', skill['tier'])
        if model:
            front['model'] = model
        if skill['meta'].get('agent'):
            front['agent'] = skill['meta']['agent']
    return front


def shared_skill_front(skill):
    # .agents/skills is read by Codex, Gemini CLI, and Cursor. Keep Agent Skills
    # spec fields; Cursor also honours disable-model-invocation.
    front = {k: v for k, v in skill['front'].items()}
    if skill['invocation'] == 'explicit':
        front['disable-model-invocation'] = True
    return front


ACRONYMS = {'kb': 'KB', 'mcp': 'MCP', 'api': 'API', 'aws': 'AWS', 'cdk': 'CDK', 'cli': 'CLI', 'rest': 'REST'}


def codex_skill_policy(skill):
    display = ' '.join(ACRONYMS.get(part, part.capitalize()) for part in skill['name'].split('-'))
    implicit = 'false' if skill['invocation'] == 'explicit' else 'true'
    return (f'{HEADER_TOML}\ninterface:\n  display_name: {json.dumps(display)}\n'
            f'policy:\n  allow_implicit_invocation: {implicit}\n')


# read-only: inspect files. execute: inspect files and run commands, no edits.
# read-write: the tool's full default tool set.
ACCESS_LEVELS = ('read-only', 'execute', 'read-write')
ACCESS_TOOLS = {
    'claude': {'read-only': 'Read, Grep, Glob', 'execute': 'Read, Grep, Glob, Bash'},
    'gemini': {'read-only': ['read_file', 'grep_search', 'glob'],
               'execute': ['read_file', 'grep_search', 'glob', 'run_shell_command']},
}
ACCESS_NOTE = {
    'read-only': ('Do not modify files, run state-changing commands, or call external services. '
                  'This agent is read-only by instruction; the parent session sandbox is the only enforcement.'),
    'execute': ('Do not modify files or call external services. You may run the commands your brief requires. '
                'These limits are instructions; the parent session sandbox is the only enforcement.'),
}


def render_claude_agent(agent, config):
    front = {'name': agent['name'], 'description': agent['front']['description']}
    if agent['access'] in ACCESS_TOOLS['claude']:
        front['tools'] = ACCESS_TOOLS['claude'][agent['access']]
    enforce = config['apply']['agents'] == 'enforce'
    front['model'] = (tool_model(config, 'claude', agent['tier']) if enforce else None) or 'inherit'
    effort = tool_effort(config, 'claude', agent['effort']) if enforce else None
    if effort:
        front['effort'] = effort
    return dump_frontmatter(front) + f'\n{HEADER_MD}\n\n' + agent['body']


def _toml_string(text):
    return json.dumps(text, ensure_ascii=False)


def render_codex_agent(agent, config):
    enforce = config['apply']['agents'] == 'enforce'
    lines = [HEADER_TOML, f"name = {_toml_string(agent['name'])}",
             f"description = {_toml_string(agent['front']['description'])}"]
    model = tool_model(config, 'codex', agent['tier']) if enforce else None
    if model:
        lines.append(f'model = {_toml_string(model)}')
    effort = tool_effort(config, 'codex', agent['effort']) if enforce else None
    if effort:
        lines.append(f'model_reasoning_effort = {_toml_string(effort)}')
    body = agent['body']
    if agent['access'] in ACCESS_NOTE:
        # Codex subagents inherit the parent sandbox; an agent file cannot restrict it.
        body = ACCESS_NOTE[agent['access']] + '\n\n' + body
    if "'''" in body:
        raise RenderError(f"{agent['name']}: body cannot contain ''' for TOML rendering")
    lines.append(f"developer_instructions = '''\n{body}'''")
    return '\n'.join(lines) + '\n'


def render_cursor_agent(agent, config):
    enforce = config['apply']['agents'] == 'enforce'
    front = {'name': agent['name'], 'description': agent['front']['description'],
             'model': (tool_model(config, 'cursor', agent['tier']) if enforce else None) or 'inherit'}
    if agent['access'] == 'read-only':
        front['readonly'] = True  # Cursor also blocks state-changing shell commands.
    return dump_frontmatter(front) + f'\n{HEADER_MD}\n\n' + agent['body']


def render_gemini_agent(agent, config):
    enforce = config['apply']['agents'] == 'enforce'
    front = {'name': agent['name'], 'description': agent['front']['description'], 'kind': 'local'}
    if agent['access'] in ACCESS_TOOLS['gemini']:
        front['tools'] = ACCESS_TOOLS['gemini'][agent['access']]
    front['model'] = (tool_model(config, 'gemini', agent['tier']) if enforce else None) or 'inherit'
    front['max_turns'] = int(agent['meta'].get('max-turns', 30))
    return dump_frontmatter(front) + f'\n{HEADER_MD}\n\n' + agent['body']


def render_rule(rule, target):
    front = rule['front']
    always = bool(front.get('always-apply', False))
    paths = front.get('paths', [])
    paths = [paths] if isinstance(paths, str) else paths
    if target == 'cursor':
        meta = {'description': front['description'], 'alwaysApply': always}
        if paths:
            meta['globs'] = ','.join(paths)
        return dump_frontmatter(meta) + f'{HEADER_MD}\n\n' + rule['body']
    if target == 'claude':
        # Without `paths`, Claude loads a rule at launch; scoped rules load on demand.
        meta = {'paths': paths} if paths else None
        prefix = dump_frontmatter(meta) if meta else ''
        return prefix + f'{HEADER_MD}\n\n' + rule['body']
    return f'{HEADER_MD}\n\n' + rule['body']


def summary(description, limit=110):
    """First sentence of a description, shortened for the always-loaded index."""
    sentence = re.split(r'(?<=[.;])\s', description.strip(), maxsplit=1)[0].rstrip('.;')
    if len(sentence) <= limit:
        return sentence + '.'
    return sentence[:limit].rsplit(' ', 1)[0].rstrip(',;:') + '…'


def tier_label(entity):
    if not entity.get('tier'):
        return ''
    effort = f"/{entity['effort']}" if entity.get('effort') else ''
    return f" [{entity['tier']}{effort}]"


def render_index(ai, entities, config):
    lines = [HEADER_MD, '']
    guidance = ai / 'project-guidance.md'
    if guidance.is_file():
        lines += [guidance.read_text().rstrip('\n'), '', '---', '']
    if entities['rules']:
        lines += ['## AI Rules', '',
                  'Apply rules marked **always-on** throughout. Read other rules when the task matches.', '']
        for rule in entities['rules']:
            always = '**Always-on:** ' if rule['front'].get('always-apply') else ''
            scope = f" Applies to `{', '.join(rule['front']['paths'])}`." if rule['front'].get('paths') else ''
            lines.append(f"- **{rule['name']}** — {always}{rule['front']['description']}{scope} "
                         f"(read `.ai/rules/{rule['name']}.md`)")
        lines.append('')
    if entities['skills']:
        lines += ['## AI Skills', '',
                  'Each tool discovers these skills natively; sources live in `.ai/skills/<name>/SKILL.md`. '
                  'Brackets show the suggested routing tier/effort. Use *explicit only* skills only when asked.', '']
        for skill in entities['skills']:
            explicit = ' *Explicit only.*' if skill['invocation'] == 'explicit' else ''
            overlay = f" Overlay: `.ai/overlays/{skill['name']}.md`." if skill['overlay'] else ''
            lines.append(f"- `{skill['name']}`{tier_label(skill)} {summary(skill['front']['description'])}"
                         f"{explicit}{overlay}")
        lines.append('')
    if entities['agents']:
        lines += ['## AI Agents', '',
                  'Delegate bounded work to these agents; sources live in `.ai/agents/<name>.md`.', '']
        for agent in entities['agents']:
            lines.append(f"- `{agent['name']}`{tier_label(agent)} {summary(agent['front']['description'])}")
        lines.append('')
    tools = [tool for tool in ('claude', 'codex', 'gemini', 'cursor')
             if tool in config['targets'] and tool in config['tools']]
    if config['tiers'] and tools:
        lines += ['## Model Routing Tiers', '',
                  'Cost hints for delegated work: use the cheapest tier whose output you can verify, '
                  'and escalate on evidence (see `model-routing`). `inherit` uses the session model.', '',
                  '| Tier | Use for | ' + ' | '.join(tools) + ' |',
                  '|---|---|' + '---|' * len(tools)]
        for tier in TIERS:
            spec = config['tiers'].get(tier)
            if not spec:
                continue
            cells = [f"`{tool_model(config, tool, tier) or 'inherit'}`" for tool in tools]
            lines.append(f"| {tier} | {spec.get('use', '')} | " + ' | '.join(cells) + ' |')
        lines.append('')
    return '\n'.join(lines).rstrip('\n') + '\n'


def build_outputs(root):
    ai = root / '.ai'
    if not ai.is_dir():
        raise RenderError(f'{ai} does not exist')
    config = load_config(ai)
    entities = load_entities(ai, config)
    targets = set(config['targets'])
    out = {}  # relative path -> bytes (file) or {relpath: (bytes, exec)} (directory)

    def text(path, content):
        out[path] = content.encode()

    index = render_index(ai, entities, config)
    # Codex and Cursor read AGENTS.md natively. Gemini CLI reads GEMINI.md, so a
    # root GEMINI.md imports AGENTS.md. Claude Code reads AGENTS.md only when no
    # CLAUDE.md exists, so it gets its own copy.
    if targets & {'agents-md', 'codex', 'cursor', 'gemini'}:
        text('AGENTS.md', index)
    if 'claude' in targets:
        text('.claude/CLAUDE.md', index)
    if 'gemini' in targets:
        text('GEMINI.md', f'{HEADER_MD}\n\n@./AGENTS.md\n')

    shared_skills = targets & {'codex', 'cursor', 'gemini'}
    for skill in entities['skills']:
        if 'claude' in targets:
            out[f".claude/skills/{skill['name']}"] = skill_files(skill, claude_skill_front(skill, config))
        if shared_skills:
            out[f".agents/skills/{skill['name']}"] = skill_files(
                skill, shared_skill_front(skill), {'agents/openai.yaml': codex_skill_policy(skill)})

    renderers = {'claude': ('.claude/agents/{}.md', render_claude_agent),
                 'codex': ('.codex/agents/{}.toml', render_codex_agent),
                 'cursor': ('.cursor/agents/{}.md', render_cursor_agent),
                 'gemini': ('.gemini/agents/{}.md', render_gemini_agent)}
    for agent in entities['agents']:
        for target, (pattern, render) in renderers.items():
            if target in targets:
                text(pattern.format(agent['name']), render(agent, config))

    for rule in entities['rules']:
        if 'cursor' in targets:
            text(f".cursor/rules/{rule['name']}.mdc", render_rule(rule, 'cursor'))
        if 'claude' in targets:
            text(f".claude/rules/{rule['name']}.md", render_rule(rule, 'claude'))

    for path in out:
        if not any(p.match(path) for p in MANAGED_PATTERNS):
            raise RenderError(f'internal error: unmanaged output path {path}')
    return out


# --- Writing -----------------------------------------------------------------

def previous_outputs(root):
    manifest = root / '.ai' / MANIFEST
    if not manifest.is_file():
        return []
    paths = []
    for line in manifest.read_text().splitlines():
        line = line.strip()
        if not line or line.startswith('#'):
            continue
        posix = PurePosixPath(line)
        if posix.is_absolute() or '..' in posix.parts or not any(
                p.match(line) for p in MANAGED_PATTERNS + LEGACY_PATTERNS):
            raise RenderError(f'{manifest}: refusing unsafe managed path {line!r}')
        paths.append(line)
    return paths


def _differs(path, content):
    if isinstance(content, bytes):
        return not path.is_file() or path.is_symlink() or path.read_bytes() != content
    if not path.is_dir() or path.is_symlink():
        return True
    actual = {f.relative_to(path).as_posix(): f for f in path.rglob('*') if f.is_file() or f.is_symlink()}
    if set(actual) != set(content):
        return True
    return any(actual[k].is_symlink() or actual[k].read_bytes() != v[0]
               or os.access(actual[k], os.X_OK) != v[1] for k, v in content.items())


def contained(root, relative):
    """Resolve root/relative, refusing symlinked components that could escape the repository.

    A symlinked `.claude/` pointing at a user-level config would otherwise let
    rendering write into, or delete from, files outside the repository.
    """
    current = root
    for part in PurePosixPath(relative).parts:
        current = current / part
        if current.is_symlink():
            raise RenderError(f'refusing to write through symlink {current.relative_to(root)}; '
                              'replace it with a real directory or remove that target from bundle.json')
    return current


def _remove(path):
    if path.is_symlink() or path.is_file():
        path.unlink()
    elif path.is_dir():
        shutil.rmtree(path)


def _prune_empty_parents(root, relative):
    """Remove empty tool directories left behind by deleted outputs, never the root."""
    parent = (root / relative).parent
    while parent != root and parent.is_dir() and not any(parent.iterdir()):
        parent.rmdir()
        parent = parent.parent


def _write(path, content):
    _remove(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    if isinstance(content, bytes):
        path.write_bytes(content)
        return
    for relative, (data, executable) in sorted(content.items()):
        file = path / relative
        file.parent.mkdir(parents=True, exist_ok=True)
        file.write_bytes(data)
        if executable:
            file.chmod(file.stat().st_mode | 0o111)


def manifest_text(outputs):
    lines = [HEADER_TOML, '# Paths are relative to the repository root and owned by .ai/render.py.']
    return '\n'.join(lines + sorted(outputs)) + '\n'


def render(root, mode='write'):
    root = Path(root).resolve()
    outputs = build_outputs(root)
    stale = [p for p in previous_outputs(root) if p not in outputs]
    changed = sorted(p for p, c in outputs.items() if _differs(root / p, c))
    manifest_path = root / '.ai' / MANIFEST
    manifest_changed = not manifest_path.is_file() or manifest_path.read_text() != manifest_text(outputs)
    # Refuse to overwrite a hand-made file that a previous render did not own.
    owned = set(previous_outputs(root))
    foreign = [p for p in changed if (root / p).exists() and p not in owned
               and not _generated_marker(root / p)]
    if foreign and mode == 'write':
        raise RenderError('refusing to overwrite files not created by the renderer: ' + ', '.join(foreign)
                          + '. Move hand-written instructions into .ai/project-guidance.md, skills into '
                          '.ai/skills/, and agents into .ai/agents/, then delete the originals and re-run.')
    if mode in ('check', 'dry-run'):
        for path in changed:
            print(f'{"stale" if mode == "check" else "write"}  {path}')
        for path in stale:
            print(f'remove {path}')
        if mode == 'check':
            dirty = bool(changed or stale or manifest_changed)
            print('outputs are stale; run python3 .ai/render.py' if dirty else 'outputs are current')
            return 1 if dirty else 0
        return 0
    for path in stale + changed:
        contained(root, path)  # validate every target before touching any of them
    for path in stale:
        _remove(root / path)
        _prune_empty_parents(root, path)
    for path in changed:
        _write(root / path, outputs[path])
    if manifest_changed:
        manifest_path.write_text(manifest_text(outputs))
    print(f'Rendered {len(outputs)} outputs ({len(changed)} changed, {len(stale)} removed) into {root}')
    return 0


def _generated_marker(path):
    file = path / 'SKILL.md' if path.is_dir() else path
    try:
        head = file.read_text(errors='replace')[:4096]
    except OSError:
        return False
    return 'Generated by .ai/render.py' in head or 'Generated by .ai/sync.sh' in head


def main(argv=None):
    parser = argparse.ArgumentParser(description='Render .ai/ guidance into assistant-specific folders.')
    parser.add_argument('--repo', default=None, help='repository root (default: parent of this .ai/ folder)')
    group = parser.add_mutually_exclusive_group()
    group.add_argument('--check', action='store_true', help='exit 1 if generated outputs are stale')
    group.add_argument('--dry-run', action='store_true', help='list changes without writing')
    args = parser.parse_args(argv)
    root = Path(args.repo) if args.repo else Path(__file__).resolve().parent.parent
    try:
        return render(root, 'check' if args.check else 'dry-run' if args.dry_run else 'write')
    except (RenderError, OSError) as error:
        print(f'Error: {error}', file=sys.stderr)
        return 1


if __name__ == '__main__':
    sys.exit(main())
